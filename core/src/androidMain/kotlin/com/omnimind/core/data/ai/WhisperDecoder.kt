package com.creativeblisslabs.omnimind.core.data.ai

import android.content.Context
import org.json.JSONObject
import java.io.InputStreamReader
import java.util.Locale

/**
 * Decodes Whisper TFLite output tokens into human-readable text and segments with timestamps.
 */
class WhisperDecoder(private val context: Context) {
    private var vocab: Map<Int, String>? = null

    data class Segment(
        val start: Float,
        val end: Float,
        val text: String,
        val language: String? = null
    )

    fun decode(tokenIds: IntArray): String {
        return decodeSegments(tokenIds).joinToString(" ") { it.text }
    }

    fun decodeSegments(tokenIds: IntArray): List<Segment> {
        val vocabMap = ensureVocab()
        val segments = mutableListOf<Segment>()
        
        var currentText = StringBuilder()
        var startTime = 0.0f
        var hasStartTime = false
        var currentLanguage: String? = null

        for (id in tokenIds) {
            when {
                id in 50259..50357 -> { // Language tokens in Whisper (e.g., <|en|>, <|es|>)
                    val token = vocabMap[id] ?: ""
                    if (token.startsWith("<|") && token.endsWith("|>")) {
                        currentLanguage = token.substring(2, token.length - 2)
                    }
                }
                id >= 50364 -> { // Timestamp tokens
                    val time = (id - 50364) * 0.02f
                    if (!hasStartTime) {
                        startTime = time
                        hasStartTime = true
                    } else {
                        val text = currentText.toString().trim()
                        if (text.isNotEmpty()) {
                            segments.add(Segment(startTime, time, text, currentLanguage))
                        }
                        currentText = StringBuilder()
                        startTime = time
                    }
                }
                id < 50257 -> { // Text tokens
                    val token = vocabMap[id] ?: ""
                    if (token.isNotEmpty()) {
                        currentText.append(token.replace("Ġ", " "))
                    }
                }
            }
        }
        
        // Catch-all for final segment if no closing timestamp
        val finalText = currentText.toString().trim()
        if (finalText.isNotEmpty()) {
            segments.add(Segment(startTime, startTime + 1.0f, finalText, currentLanguage))
        }

        return segments
    }

    fun toSrt(segments: List<Segment>): String {
        return buildString {
            segments.forEachIndexed { index, segment ->
                appendLine(index + 1)
                appendLine("${formatTime(segment.start)} --> ${formatTime(segment.end)}")
                appendLine(segment.text)
                appendLine()
            }
        }
    }

    fun toVtt(segments: List<Segment>): String {
        return buildString {
            appendLine("WEBVTT")
            appendLine()
            segments.forEach { segment ->
                appendLine("${formatTime(segment.start, ".")} --> ${formatTime(segment.end, ".")}")
                appendLine(segment.text)
                appendLine()
            }
        }
    }

    fun toChapters(segments: List<Segment>): String {
        return buildString {
            appendLine("; Chapters generated by OmniMind Whisper")
            // Create a chapter for each segment or group segments into logical chunks
            segments.forEachIndexed { index, segment ->
                appendLine("[CHAPTER]")
                appendLine("TIMEBASE=1/1000")
                appendLine("START=${(segment.start * 1000).toLong()}")
                appendLine("END=${(segment.end * 1000).toLong()}")
                appendLine("title=Chapter ${index + 1}: ${segment.text.take(30)}...")
                appendLine()
            }
        }
    }

    private fun formatTime(seconds: Float, decimalSeparator: String = ","): String {
        val hrs = (seconds / 3600).toInt()
        val mins = ((seconds % 3600) / 60).toInt()
        val secs = (seconds % 60).toInt()
        val ms = ((seconds % 1) * 1000).toInt()
        return String.format(Locale.US, "%02d:%02d:%02d%s%03d", hrs, mins, secs, decimalSeparator, ms)
    }

    private fun ensureVocab(): Map<Int, String> {
        vocab?.let { return it }
        
        val map = mutableMapOf<Int, String>()
        try {
            val assetManager = context.assets
            val inputStream = assetManager.open("whisper_vocab.json")
            val reader = InputStreamReader(inputStream)
            val json = JSONObject(reader.readText())
            
            json.keys().forEach { key ->
                val id = json.getInt(key)
                map[id] = key
            }
        } catch (e: Exception) {
            android.util.Log.e("WhisperDecoder", "Failed to load vocab: ${e.message}")
            for (i in 0..255) map[i] = i.toChar().toString()
        }
        
        return map.also { vocab = it }
    }
}
